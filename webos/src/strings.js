/** Texte de l'app TV, sinon celui du site (même remplacement des {param}). */
export function tt(key, params) {
  const own = TV[lang()]?.[key] ?? TV.en[key]
  if (own === undefined) return t(key, params)
  let s = own
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}
